-- 2. Submit an event and get the status token back. Since 006 the token is
--    always generated by the server and anon cannot read submissions, so a
--    direct insert cannot return it. SECURITY DEFINER for that read-back
--    only; the row still goes through the insert triggers and constraints
--    (link or text required, https only, length limits).
CREATE OR REPLACE FUNCTION public.submit_event(
  p_source_url TEXT,
  p_raw_text TEXT,
  p_note TEXT
)
RETURNS TABLE (id UUID, access_token UUID)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  INSERT INTO public.submissions AS s (source_url, raw_text, note)
  VALUES (
    NULLIF(trim(p_source_url), ''),
    NULLIF(trim(p_raw_text), ''),
    NULLIF(trim(p_note), '')
  )
  RETURNING s.id, s.access_token;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_event(TEXT, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_event(TEXT, TEXT, TEXT)
  TO anon, authenticated, service_role;

-- 3. Abuse floor for anonymous submissions: at most 60 per rolling hour in
--    total. Like the report limit in 006, the database has no identity for
--    anonymous callers, so this bounds a flood rather than one person; a
--    per-device limit needs an Edge Function (IP or Turnstile) and waits
--    until abuse appears. Service-role jobs are not limited.
--    ERRCODE PT429 makes PostgREST answer HTTP 429.
CREATE INDEX IF NOT EXISTS idx_submissions_anon_created
  ON public.submissions (created_at)
  WHERE submitter_user_id IS NULL;

CREATE OR REPLACE FUNCTION public.limit_submission_rate()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  recent INTEGER;
BEGIN
  IF auth.jwt() ->> 'role' = 'anon' THEN
    PERFORM pg_advisory_xact_lock(hashtext('submissions:anon'));
    SELECT count(*) INTO recent
    FROM public.submissions
    WHERE submitter_user_id IS NULL
      AND created_at > now() - interval '1 hour';
    IF recent >= 60 THEN
      RAISE EXCEPTION 'too many suggestions right now, try again later'
        USING ERRCODE = 'PT429';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.limit_submission_rate() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS submissions_rate_limit ON public.submissions;
CREATE TRIGGER submissions_rate_limit
  BEFORE INSERT ON public.submissions
  FOR EACH ROW EXECUTE FUNCTION public.limit_submission_rate();

-- 4. Coverage: upcoming published events per city and topic, so curators
--    can see gaps ("Bamenda, agriculture: 0"). Online events count under
--    'Online'. Curators only. SECURITY INVOKER: RLS on events still applies.
CREATE OR REPLACE FUNCTION public.curation_coverage()
RETURNS TABLE (city TEXT, topic_id TEXT, upcoming INTEGER)
LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'only curators can read coverage' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT
    CASE WHEN e.format = 'virtual' THEN 'Online'
         ELSE COALESCE(NULLIF(trim(e.city), ''), 'City not stated')
    END AS city,
    et.topic_id,
    count(*)::INTEGER AS upcoming
  FROM public.events e
  JOIN public.event_topics et ON et.event_id = e.id
  WHERE e.publication_status = 'published'
    AND e.start_at >= now()
  GROUP BY 1, 2;
END;
$$;

REVOKE ALL ON FUNCTION public.curation_coverage() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.curation_coverage() TO authenticated, service_role;
