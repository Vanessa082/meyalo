ALTER TABLE public.submissions
  ADD CONSTRAINT submissions_raw_text_length
  CHECK (raw_text IS NULL OR char_length(raw_text) <= 5000);

-- 7. Report rate limit, over a rolling hour.
--    Signed-in callers: at most 10 reports per user.
--    Anonymous callers: the database has no identity for them (no IP, and
--    client_request_id is chosen by the client), so the cap is per event:
--    at most 20 anonymous reports per event. This bounds a flood on one event
--    but does not stop one person spreading reports across events, and a
--    flood can use up the anonymous allowance for that event. A per-device
--    limit needs an Edge Function (IP or Turnstile) and is deferred until
--    abuse appears.
--    Service-role jobs and migrations (no client JWT role) are not limited.
--    SECURITY DEFINER because clients cannot read reports to count them.
--    The advisory lock serializes concurrent inserts for the same key so the
--    count cannot be raced past the limit.
--    ERRCODE PT429 makes PostgREST answer HTTP 429.
CREATE INDEX IF NOT EXISTS idx_reports_reporter_created
  ON public.reports (reporter_user_id, created_at)
  WHERE reporter_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_reports_event_anon_created
  ON public.reports (event_id, created_at)
  WHERE reporter_user_id IS NULL;

CREATE OR REPLACE FUNCTION public.limit_report_rate()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller_role TEXT := auth.jwt() ->> 'role';
  recent INTEGER;
BEGIN
  IF NEW.reporter_user_id IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(hashtext('reports:user:' || NEW.reporter_user_id::text));
    SELECT count(*) INTO recent
    FROM public.reports
    WHERE reporter_user_id = NEW.reporter_user_id
      AND created_at > now() - interval '1 hour';
    IF recent >= 10 THEN
      RAISE EXCEPTION 'too many reports, try again later'
        USING ERRCODE = 'PT429';
    END IF;
  ELSIF caller_role = 'anon' THEN
    PERFORM pg_advisory_xact_lock(hashtext('reports:anon:' || NEW.event_id::text));
    SELECT count(*) INTO recent
    FROM public.reports
    WHERE event_id = NEW.event_id
      AND reporter_user_id IS NULL
      AND created_at > now() - interval '1 hour';
    IF recent >= 20 THEN
      RAISE EXCEPTION 'too many reports for this event, try again later'
        USING ERRCODE = 'PT429';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.limit_report_rate() FROM PUBLIC, anon, authenticated;

-- Runs after reports_protect_insert (triggers fire in name order), so
-- reporter_user_id is already the server-side auth.uid().
DROP TRIGGER IF EXISTS reports_rate_limit ON public.reports;
CREATE TRIGGER reports_rate_limit
  BEFORE INSERT ON public.reports
  FOR EACH ROW EXECUTE FUNCTION public.limit_report_rate();
