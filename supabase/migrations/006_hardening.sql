-- 1. Public event view without curator and provenance columns.
--    security_invoker: the caller's RLS on events applies, so the view shows
--    exactly what events_public_select allows. Columns are listed by name so a
--    column added to events later is not exposed until it is added here.
--    This view alone does not hide checked_by: anon still has SELECT on the
--    events table. Revoking those columns waits until the app reads this view
--    (the app currently selects events.*).
CREATE OR REPLACE VIEW public.events_public
WITH (security_invoker = true)
AS
SELECT
  id,
  title,
  description,
  format,
  category,
  start_at,
  end_at,
  timezone,
  registration_deadline,
  city,
  country_code,
  venue_name,
  address,
  latitude,
  longitude,
  virtual_access_type,
  organizer_id,
  organizer_name,
  source_url,
  source_type,
  registration_url,
  price_type,
  currency,
  price_min,
  price_max,
  verification_state,
  publication_status,
  last_checked_at,
  created_at,
  updated_at
FROM public.events
WHERE publication_status = 'published'
  AND verification_state IN ('source_confirmed', 'organizer_confirmed');

REVOKE ALL ON TABLE public.events_public FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.events_public TO anon, authenticated, service_role;

-- 2. Organizers are public only while they have a public event.
--    Curators keep full access through organizers_admin_write (FOR ALL).
DROP POLICY IF EXISTS organizers_public_select ON public.organizers;
CREATE POLICY organizers_public_select ON public.organizers
  FOR SELECT TO anon, authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.events AS event
      WHERE event.organizer_id = organizers.id
        AND event.publication_status = 'published'
        AND event.verification_state IN ('source_confirmed', 'organizer_confirmed')
    )
  );

-- 3. Reports target public events only.
DROP POLICY IF EXISTS reports_insert ON public.reports;
CREATE POLICY reports_insert ON public.reports
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.events AS event
      WHERE event.id = reports.event_id
        AND event.publication_status = 'published'
        AND event.verification_state IN ('source_confirmed', 'organizer_confirmed')
    )
  );

-- 4. Idempotent report replay from the offline outbox. NULLs do not collide,
--    so reports without a request id are unaffected.
ALTER TABLE public.reports
  ADD COLUMN IF NOT EXISTS client_request_id UUID;

ALTER TABLE public.reports
  DROP CONSTRAINT IF EXISTS reports_event_client_request_unique;
ALTER TABLE public.reports
  ADD CONSTRAINT reports_event_client_request_unique
  UNIQUE (event_id, client_request_id);

-- 5. The submission access token is always generated by the server.
--    Consequence: an anonymous submitter cannot read the token back through
--    a direct insert (anon has no SELECT on submissions). The /submit flow
--    needs a SECURITY DEFINER function that inserts and returns (id, token).
CREATE OR REPLACE FUNCTION public.protect_submission_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.access_token = gen_random_uuid();
  IF NOT public.is_admin() THEN
    NEW.status = 'under_review';
    NEW.extracted = NULL;
    NEW.decision_reason = NULL;
    NEW.published_event_id = NULL;
    NEW.submitter_user_id = auth.uid();
  END IF;
  RETURN NEW;
END;
$$;

-- 6. Length limits on client free text. Existing rows must satisfy them;
--    on the remote project, check first:
--      SELECT count(*) FROM reports WHERE char_length(note) > 500; (and so on)
ALTER TABLE public.reports DROP CONSTRAINT IF EXISTS reports_note_length;
ALTER TABLE public.reports
  ADD CONSTRAINT reports_note_length
  CHECK (note IS NULL OR char_length(note) <= 500);

ALTER TABLE public.feedback DROP CONSTRAINT IF EXISTS feedback_message_length;
ALTER TABLE public.feedback
  ADD CONSTRAINT feedback_message_length
  CHECK (char_length(message) <= 2000);

ALTER TABLE public.feedback DROP CONSTRAINT IF EXISTS feedback_reply_email_length;
ALTER TABLE public.feedback
  ADD CONSTRAINT feedback_reply_email_length
  CHECK (reply_email IS NULL OR char_length(reply_email) <= 254);

ALTER TABLE public.submissions DROP CONSTRAINT IF EXISTS submissions_note_length;
ALTER TABLE public.submissions
  ADD CONSTRAINT submissions_note_length
  CHECK (note IS NULL OR char_length(note) <= 1000);

