-- What anonymous and signed-in non-curator clients can write.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;

SELECT plan(11);

INSERT INTO public.organizers (id, name)
VALUES ('a0000000-0000-4000-8000-000000000011', 'pgtap write organizer');

INSERT INTO public.events (
  id, title, description, format, category, start_at, city, country_code,
  organizer_name, organizer_id, source_url, source_type,
  publication_status, verification_state
) VALUES
  ('b0000000-0000-4000-8000-000000000011', 'pgtap published', 'fixture',
   'in_person', 'Test', now() + interval '1 day', 'Buea', 'CM',
   'pgtap write organizer', 'a0000000-0000-4000-8000-000000000011',
   'https://example.com/pgtap-write-published', 'organizer_site',
   'published', 'source_confirmed'),
  ('b0000000-0000-4000-8000-000000000012', 'pgtap draft', 'fixture',
   'in_person', 'Test', now() + interval '1 day', 'Buea', 'CM',
   'pgtap write organizer', 'a0000000-0000-4000-8000-000000000011',
   'https://example.com/pgtap-write-draft', 'organizer_site',
   'draft', 'unreviewed');

INSERT INTO auth.users (id, email)
VALUES ('c0000000-0000-4000-8000-000000000011', 'pgtap-writer@meyalo.local');

-- Anonymous reports and submissions.
SET LOCAL ROLE anon;
SET LOCAL request.jwt.claims TO '{"role":"anon"}';

SELECT lives_ok(
  $$ INSERT INTO public.reports (event_id, reason, client_request_id, consent_version, consent_language, age_group)
     VALUES ('b0000000-0000-4000-8000-000000000011', 'scam',
             'd0000000-0000-4000-8000-000000000011', '2026-10-19', 'fr', '18_plus') $$,
  'anon can report a published event'
);
SELECT throws_ok(
  $$ INSERT INTO public.reports (event_id, reason, client_request_id, consent_version, consent_language, age_group)
     VALUES ('b0000000-0000-4000-8000-000000000011', 'scam',
             'd0000000-0000-4000-8000-000000000011', '2026-10-19', 'fr', '18_plus') $$,
  '23505', NULL,
  'replaying the same client_request_id for an event is rejected'
);
SELECT throws_ok(
  $$ INSERT INTO public.reports (event_id, reason, consent_version, consent_language, age_group)
     VALUES ('b0000000-0000-4000-8000-000000000012', 'scam', '2026-10-19', 'fr', '18_plus') $$,
  '42501', NULL,
  'anon cannot report a draft event'
);
SELECT lives_ok(
  $$ INSERT INTO public.submissions (source_url, access_token)
     VALUES ('https://example.com/pgtap-chosen-token',
             '00000000-0000-0000-0000-000000000001') $$,
  'anon can submit an event'
);

RESET ROLE;

SELECT isnt(
  (SELECT access_token FROM public.submissions
   WHERE source_url = 'https://example.com/pgtap-chosen-token'),
  '00000000-0000-0000-0000-000000000001'::uuid,
  'submission access_token is generated by the server, not the client'
);

-- A signed-in user without the curator role.
SET LOCAL ROLE authenticated;
SET LOCAL request.jwt.claims TO
  '{"sub":"c0000000-0000-4000-8000-000000000011","role":"authenticated"}';

SELECT throws_ok(
  $$ INSERT INTO public.events (
       title, description, format, category, start_at, city,
       organizer_name, source_url, source_type)
     VALUES ('pgtap forged', 'x', 'in_person', 'Test', now() + interval '1 day',
             'Buea', 'x', 'https://example.com/pgtap-forged', 'organizer_site') $$,
  '42501', NULL,
  'a non-curator cannot create events'
);
SELECT is_empty(
  $$ UPDATE public.events SET title = 'pgtap hijacked'
     WHERE id = 'b0000000-0000-4000-8000-000000000011' RETURNING id $$,
  'a non-curator cannot update a published event'
);
SELECT is_empty(
  $$ DELETE FROM public.events
     WHERE id = 'b0000000-0000-4000-8000-000000000011' RETURNING id $$,
  'a non-curator cannot delete a published event'
);
SELECT throws_ok(
  $$ INSERT INTO public.user_roles (user_id, role)
     VALUES ('c0000000-0000-4000-8000-000000000011', 'admin') $$,
  '42501', NULL,
  'a non-curator cannot grant themselves the curator role'
);
SELECT is(public.is_admin(), false, 'the non-curator is still not a curator');

RESET ROLE;

SELECT is(
  (SELECT title FROM public.events WHERE id = 'b0000000-0000-4000-8000-000000000011'),
  'pgtap published',
  'the published event is unchanged'
);

SELECT * FROM finish();
ROLLBACK;
